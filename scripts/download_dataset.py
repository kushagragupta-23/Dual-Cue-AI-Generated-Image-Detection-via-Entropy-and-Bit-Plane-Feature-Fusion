def save_provenance_manifest(target_dir: Path, provenance: dict, real_count: int, ai_count: int):
    """Save a provenance_manifest.json documenting the dataset origin."""
    manifest = {
        **provenance,
        "download_timestamp": datetime.now(timezone.utc).isoformat(),
        "image_counts": {
            "real": real_count,
            "ai_generated": ai_count,
            "total": real_count + ai_count
        },
        "dataset_location": str(target_dir.resolve()),
        "folder_structure": {
            "0_real/": f"{real_count} verified real photographs",
            "1_ai_generated/": f"{ai_count} verified AI-generated images"
        },
        "labeling_method": (
            "Deterministic folder-based labeling. All images in '0_real/' are labeled 0 (Real). "
            "All images in '1_ai_generated/' are labeled 1 (AI-Generated). Labels are inherited "
            "from the upstream academic dataset's own verified annotations."
        )
    }

    manifest_path = target_dir / "provenance_manifest.json"
    with open(manifest_path, "w", encoding="utf-8") as f:
        json.dump(manifest, f, indent=2, ensure_ascii=False)
    logger.info(f"Provenance manifest saved to: {manifest_path}")
    return manifest_path


