# STRATEGY 1: HuggingFace dima806/ai_vs_real_image_detection
# ============================================================================

def download_dima806(target_dir: Path, num_per_class: int = 700) -> bool:
    """
    Download verified Real vs. AI-generated images from HuggingFace Hub.
    Dataset: dima806/ai_vs_real_image_detection
    Label 0 = Real photograph, Label 1 = AI-generated
    """
    try:
        import datasets

        logger.info("=" * 70)
        logger.info("STRATEGY 1: Downloading from 'dima806/ai_vs_real_image_detection'")
        logger.info("=" * 70)
        logger.info("Connecting to HuggingFace Hub (streaming mode)...")

        ds = datasets.load_dataset(
            "Hemg/ai-vs-real-image-detection",
            split="train",
            streaming=True
        )

        real_dir = target_dir / "0_real"
        ai_dir = target_dir / "1_ai_generated"
        real_dir.mkdir(parents=True, exist_ok=True)
        ai_dir.mkdir(parents=True, exist_ok=True)

        real_count, ai_count = 0, 0
        logger.info(f"Downloading {num_per_class} Real + {num_per_class} AI images...")

        for item in ds:
            label = item.get("label", -1)
            img = item.get("image")
            if img is None:
                continue

            if label == 0 and real_count < num_per_class:
                save_path = real_dir / f"real_{real_count:04d}.png"
                img.convert("RGB").save(save_path)
                real_count += 1
                if real_count % 50 == 0:
                    logger.info(f"  Real: {real_count}/{num_per_class} downloaded")

            elif label == 1 and ai_count < num_per_class:
                save_path = ai_dir / f"ai_{ai_count:04d}.png"
                img.convert("RGB").save(save_path)
                ai_count += 1
                if ai_count % 50 == 0:
                    logger.info(f"  AI:   {ai_count}/{num_per_class} downloaded")

            if real_count >= num_per_class and ai_count >= num_per_class:
                break

        if real_count >= num_per_class and ai_count >= num_per_class:
            logger.info(f"SUCCESS: Downloaded {real_count} Real + {ai_count} AI images")
            save_provenance_manifest(target_dir, PROVENANCE_DIMA806, real_count, ai_count)
            return True
        else:
            logger.warning(f"Incomplete download: {real_count} Real, {ai_count} AI. Falling back...")
            return False

    except ImportError:
        logger.warning("'datasets' library not installed. Run: pip install datasets")
        return False
    except Exception as e:
        logger.error(f"Download failed: {e}")
        return False


