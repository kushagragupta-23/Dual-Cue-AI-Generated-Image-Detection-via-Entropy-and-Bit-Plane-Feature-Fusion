def main():
    parser = argparse.ArgumentParser(
        description="Download Verified Real vs. AI-Generated Image Dataset"
    )
    parser.add_argument(
        "--target_dir", type=str, default="outputs/verified_dataset",
        help="Directory to save downloaded images"
    )
    parser.add_argument(
        "--num_images", type=int, default=1400,
        help="Total number of images (split 50/50 between Real and AI)"
    )
    parser.add_argument(
        "--source", type=str, choices=["auto", "dima806", "cifake", "local"],
        default="auto",
        help="Data source: auto (try all), dima806, cifake, or local placeholder"
    )
    args = parser.parse_args()

    target_path = root_path / args.target_dir
    num_per_class = args.num_images // 2

    logger.info(f"Target: {target_path.resolve()}")
    logger.info(f"Requested: {num_per_class} Real + {num_per_class} AI = {args.num_images} total")

    success = False

    if args.source in ("auto", "dima806"):
        success = download_dima806(target_path, num_per_class)

    if not success and args.source in ("auto", "cifake"):
        success = download_cifake(target_path, num_per_class)

    if not success:
        logger.warning("All remote sources failed. Falling back to local placeholder generation.")
        generate_local_placeholder(target_path, args.num_images)

    # Final verification
    real_dir = target_path / "0_real"
    ai_dir = target_path / "1_ai_generated"
    real_count = len(list(real_dir.glob("*.png"))) if real_dir.exists() else 0
    ai_count = len(list(ai_dir.glob("*.png"))) if ai_dir.exists() else 0

    print("\n" + "=" * 80)
    print("DATASET DOWNLOAD COMPLETE")
    print("=" * 80)
    print(f"  Location:    {target_path.resolve()}")
    print(f"  Real images: {real_count}  (in 0_real/)")
    print(f"  AI images:   {ai_count}  (in 1_ai_generated/)")
    print(f"  Total:       {real_count + ai_count}")
    print(f"  Provenance:  {target_path / 'provenance_manifest.json'}")
    print()
    print("To train on this dataset, run:")
    print(f"  python scripts/train.py --data_dir {args.target_dir} --epochs 5 --batch_size 8")
    print()
    print("To run the full pipeline, run:")
    print(f"  python scripts/run_project.py --data_dir {args.target_dir} --batch_size 8 --export_visualizations")
    print("=" * 80 + "\n")


if __name__ == "__main__":
    main()
