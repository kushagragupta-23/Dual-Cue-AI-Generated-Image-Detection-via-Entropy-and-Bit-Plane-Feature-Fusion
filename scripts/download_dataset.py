def generate_local_placeholder(target_dir: Path, total_samples: int = 1400) -> None:
    """
    Generate placeholder images for offline pipeline testing ONLY.
    WARNING: These are NOT real photographs or AI-generated images.
    """
    logger.warning("=" * 70)
    logger.warning("EMERGENCY FALLBACK: Generating LOCAL PLACEHOLDER images")
    logger.warning("These are NOT real photos or AI images!")
    logger.warning("Use ONLY for testing pipeline mechanics, NOT for research validation!")
    logger.warning("=" * 70)

    num_per_class = total_samples // 2

    real_dir = target_dir / "0_real"
    ai_dir = target_dir / "1_ai_generated"
    real_dir.mkdir(parents=True, exist_ok=True)
    ai_dir.mkdir(parents=True, exist_ok=True)

    rng = random.Random(42)
    start_time = time.time()

    for i in range(num_per_class):
        w, h = rng.choice([256, 280, 320]), rng.choice([256, 280, 320])
        base = (rng.randint(50, 100), rng.randint(110, 160), rng.randint(60, 100))
        img = Image.new("RGB", (w, h), color=base)
        draw = ImageDraw.Draw(img)
        step = rng.choice([8, 12, 16])
        for y in range(0, h, step):
            for x in range(0, w, step):
                if (x // step + y // step) % 2 == 0:
                    c = tuple(min(255, max(0, base[ch] + rng.randint(-20, 20))) for ch in range(3))
                    draw.rectangle([x, y, x + step - 1, y + step - 1], fill=c)
        for _ in range(w * h // 10):
            nx, ny = rng.randint(0, w - 1), rng.randint(0, h - 1)
            draw.point((nx, ny), fill=tuple(rng.randint(0, 8) for _ in range(3)))
        img.save(real_dir / f"real_{i:04d}.png")

    for i in range(num_per_class):
        w, h = rng.choice([256, 280, 320]), rng.choice([256, 280, 320])
        base = (rng.randint(180, 230), rng.randint(50, 100), rng.randint(50, 100))
        img = Image.new("RGB", (w, h), color=base)
        draw = ImageDraw.Draw(img)
        step = rng.choice([16, 24, 32])
        for y in range(0, h, step):
            for x in range(0, w, step):
                if (x // step + y // step) % 2 == 0:
                    c = tuple(min(255, max(0, base[ch] + rng.randint(-30, 30))) for ch in range(3))
                    draw.rectangle([x, y, x + step - 1, y + step - 1], fill=c)
        for _ in range(w * h // 15):
            nx, ny = rng.randint(0, w - 1), rng.randint(0, h - 1)
            draw.point((nx, ny), fill=tuple(rng.randint(0, 40) for _ in range(3)))
        img.save(ai_dir / f"ai_{i:04d}.png")

    elapsed = time.time() - start_time
    logger.info(f"Generated {total_samples} placeholder images in {elapsed:.1f}s")
    save_provenance_manifest(target_dir, PROVENANCE_LOCAL, num_per_class, num_per_class)


